const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const G = require('../calculations.js');
const C = require('../core.js');
const vm = require('node:vm');
const fixture = JSON.parse(fs.readFileSync(path.join(__dirname,'fixtures/control-node-1.json'),'utf8'));
const cell = address => fixture.cells[address].value;
const close = (actual,expected) => assert.ok(actual !== null && Math.abs(actual-expected) <= Math.max(1e-18,Math.abs(expected)*1e-10),`${actual} != ${expected}`);
for (const [height,alpha,result] of [['C15','C27','C28'],['C60','C65','C66'],['C87','C86','C88'],['C99','C95','C100']]) {
  close(G.linearExpansion(cell(height),cell(alpha),cell('C5'),20).value,cell(result));
}
for (const mode of ['I','J']) {
  const denominator = [4,10,11,17,5,6,7,8,9].reduce((sum,row)=>sum+cell(mode+row),0);
  close(G.thermalForce(cell(mode+'23'),cell(mode+'22'),denominator).value,cell(mode+'32'));
}
close(G.linearExpansion(100,12,120,20).value,0.12);
close(G.linearExpansion(100,12,20,20).value,0);
close(G.linearExpansion(100,12,-20,20).value,-0.048);
close(G.linearExpansion(100,0,120,20).value,0);
close(G.thermalForce(0.12,0.10,1e-7).value,200000);
close(G.thermalForce(0,0,1e-7).value,0);
close(G.thermalForce(0.10,0.12,1e-7).value,-200000);
assert.equal(G.linearExpansion('',12,120,20).value,null);
assert.equal(G.linearExpansion(100,null,20,20).value,null,'Unknown coefficient is not silently assumed zero');
assert.equal(G.linearExpansion(100,12,120,null).value,null,'Reference temperature must be explicit');
assert.equal(G.linearExpansion(100,12,-300,20).value,null);
assert.equal(G.thermalForce(0,null,1e-7).value,null);
assert.equal(G.thermalForce(0.1,0.1,0).value,null);
assert.equal(G.thermalForce(0.1,0.1,-1).value,null);
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../standards.bundle.js'),'utf8'),context);
const catalog = context.FlangeStandardsDB;
const materials = [['Кріплення',215,212,11.5],['Кришка',110,110,10],['Корпус',200,197,11.5]].map(([name,cold,warm,alpha])=>({name,grades:[{kp:'',description:name,data:{E:{20:cold,50:warm,100:warm},Alpha:{20:alpha,50:alpha,100:alpha}}}]}));
const node = C.createNode('Температурна перевірка');
node.operating.normal.temperature = '45'; node.operating.hydro.temperature = '90';
node.gasket = {...node.gasket,outerDiameter:'1300',innerDiameter:'1150',thickness:'2',hasHoles:true,holeDiameter:'24'};
node.fastener.nominalDiameter = '24'; node.fastener.count = '32';
node.connection.sideA.height = '55'; node.connection.sideB.height = '36'; node.washers.placement = 'a';
node.fastener.material = C.materialRef(materials[0],materials[0].grades[0]);
node.washers.material = node.fastener.material;
node.connection.sideA.material = C.materialRef(materials[1],materials[1].grades[0]);
node.connection.sideB.material = C.materialRef(materials[2],materials[2].grades[0]);
let result = G.nodeThermal(node,materials,catalog);
close(result.normal.values.gasket,2*0.21*25*1e-6);
close(result.normal.values.pack,0.0149105);
assert.equal(result.normal.values.fastener,0);
assert.equal(result.normal.sources.find(source=>source.name==='Прокладка').temperature,50);
close(result.normal.values.force,result.normal.values.pack / result.normal.totalCompliance);
assert.equal(result.hydro.values.force,0,'HV force stays zero even at 90°C');
assert.equal(result.hydro.values.pack,0);
node.operating.normal.temperature = '90';
result = G.nodeThermal(node,materials,catalog);
close(result.normal.values.gasket,2*0.43*70*1e-6);
assert.equal(result.normal.values.fastener,0);
assert.equal(result.normal.sources.find(source=>source.name==='Прокладка').temperature,100);
node.operating.normal.temperature = '20';
assert.equal(G.nodeThermal(node,materials,catalog).normal.values.force,0);
node.operating.normal.temperature = '45'; node.fastener.type = 'bolt';
close(G.nodeThermal(node,materials,catalog).normal.values.sideB,0.01035);
node.fastener.type = 'stud';
const baseline = G.nodeThermal(node,materials,catalog).normal;
const spacer = {name:'Проставка',grades:[{kp:'',description:'Проставка',data:{E:{20:200,50:200}}}]};
materials.push(spacer);
node.extras.push({name:'Проставка',thickness:'5',area:'10000',material:C.materialRef(spacer,spacer.grades[0])});
result = G.nodeThermal(node,materials,catalog);
close(result.normal.values.pack,baseline.values.pack);
assert.ok(result.normal.values.force < baseline.values.force,'Spacers influence thermal force through compliance only');
node.extras = [];
node.operating.normal.temperature = '450';
result = G.nodeThermal(node,materials,catalog);
assert.equal(result.normal.values.force,null);
assert.equal(result.hydro.values.force,0);
node.operating.normal.temperature = '45';
materials[1].grades[0].data.E = {};
result = G.nodeThermal(node,materials,catalog);
assert.notEqual(result.normal.values.pack,null);
assert.equal(result.normal.values.force,null,'Unknown E must not produce a normal-mode force');
materials[1].grades[0].data.Alpha = {};
result = G.nodeThermal(node,materials,catalog);
assert.equal(result.normal.values.pack,null);
assert.equal(result.hydro.values.force,0);
console.log('OK: таблична α в більшу сторону, нуль кріплення/ГВ, пакет деталей, проставки, температурні сили та відсутні дані.');
