const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const C = require('../core.js');
const G = require('../calculations.js');
const fixture = require('./fixtures/control-node-1.json');
const cell = address => fixture.cells[address].value;
const close = (a,b) => assert.ok(a !== null && Math.abs(a-b) <= Math.max(1e-10,Math.abs(b)*1e-10),`${a} != ${b}`);
const sourceInput = (column,inputs) => ({gasketArea:cell('C22'),pressureArea:cell('C23'),pressure:cell(inputs+'4'),mediumCoefficient:cell(inputs+'21'),seatingPressure:cell(inputs+'20'),minimumPressure:cell(inputs+'25'),maximumPressure:cell('C26'),count:cell('C40'),diameter:cell('C34'),friction:cell('C41'),torqueNm:cell('C6')/1000,loadFactor:cell(column+'18'),thermalForce:cell(column+'32')});
for (const [column,inputs] of [['I','C'],['J','D']]) {
  const result = G.forces(sourceInput(column,inputs));
  for (const [key,row] of [['initialSingle',27],['initialTotal',28],['sealing',29],['hydrostatic',30],['seating',31],['fastener',33],['gasket',34],['sealingRequired',43],['contactPressure',44]]) close(result.values[key],cell(column+row));
  assert.ok(Object.values(result.checks).every(check=>check.passed === true));
}
const base = sourceInput('I','C');
const sourceNormal = G.forces(base).values, sourceHydro = G.forces(sourceInput('J','D')).values;
close(sourceHydro.pressureRequired,cell('O55'));
const sourceMinimum = Math.max(sourceNormal.seating,sourceNormal.sealingRequired,sourceHydro.sealingRequired,sourceNormal.pressureRequired,sourceHydro.pressureRequired);
close(sourceMinimum,cell('N57'));
close(sourceMinimum*cell('C41')*cell('C34')/(cell('C40')*1000),cell('N58'));
assert.equal(Math.ceil(cell('N58')),cell('P88'));
let result = G.forces({...base,torqueNm:''});
assert.equal(result.values.initialTotal,null);
assert.equal(result.checks.seating.passed,null);
close(result.values.pressureRequired,cell('N55'));
result = G.forces({...base,torqueNm:0});
assert.equal(result.values.initialTotal,0);
assert.equal(result.checks.seating.passed,false);
assert.equal(result.checks.minimumPressure.passed,false);
assert.ok(result.values.contactPressure < 0,'Retain signed unloading; never clamp negative contact pressure to a pass');
assert.equal(G.forces({...base,torqueNm:10000}).checks.maximumPressure.passed,false);
for (const change of [{count:'1.5'},{diameter:0},{friction:0},{torqueNm:-1}]) assert.equal(G.forces({...base,...change}).values.initialTotal,null);
assert.equal(G.forces({...base,pressure:-1}).values.hydrostatic,null);
assert.equal(G.forces({...base,loadFactor:null}).values.gasket,null);
assert.equal(G.forces({...base,thermalForce:null}).values.sealingRequired,null);
assert.equal(G.forces({...base,mediumCoefficient:null}).values.sealing,null);
close(G.forces({...base,pressure:0}).values.hydrostatic,0);
// Exact boundaries are inclusive; no rounding before a check.
const boundary = {gasketArea:1,pressureArea:1,pressure:0,mediumCoefficient:1,seatingPressure:5,minimumPressure:5,maximumPressure:5,count:1,diameter:1,friction:1,torqueNm:0.005,loadFactor:0.5,thermalForce:0};
assert.ok(Object.values(G.forces(boundary).checks).every(check=>check.passed));
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../standards.bundle.js'),'utf8'),context);
const catalog = context.FlangeStandardsDB;
const material = {name:'Тестова сталь',grades:[{kp:'',description:'Тест',data:{E:{20:200,50:200},Alpha:{20:12,50:12}}}]};
const materials = [material];
const node = C.createNode('Тест нижньої межі');
node.operating = {normal:{pressure:'0.6',temperature:'45',medium:'Рідина'},hydro:{pressure:'0.85',temperature:'20',medium:'Вода'}};
Object.assign(node.gasket,{thickness:'2',outerDiameter:'1300',innerDiameter:'1150',hasHoles:true,holeDiameter:'24'});
Object.assign(node.fastener,{nominalDiameter:'24',count:'32'});
for (const part of [node.fastener,node.connection.sideA,node.connection.sideB]) part.material = C.materialRef(material,material.grades[0]);
node.connection.sideA.height = '55'; node.connection.sideB.height = '36';
result = G.nodeForces(node,materials,catalog);
assert.notEqual(result.minimum.torqueNm,null,'Minimum is independent of entered torque');
assert.equal(result.states.normal.values.initialTotal,null);
const min = result.minimum;
close(min.force,Math.max(...min.candidates.map(item=>item.force)));
close(min.torqueNm,min.force*0.26*24/(32*1000));
assert.equal(min.roundedTorqueNm,Math.ceil(min.torqueNm),'Same upward rounding as Excel P88');
assert.ok(min.governing.length > 0);
node.fastener.torqueNm = String(min.torqueNm*(1+1e-12));
assert.ok(['normal','hydro'].every(mode=>Object.values(G.nodeForces(node,materials,catalog).states[mode].checks).every(check=>check.passed)));
node.fastener.lubricated = false;
close(G.nodeForces(node,materials,catalog).minimum.torqueNm,min.torqueNm*0.37/0.26);
node.operating.hydro.medium = '';
assert.equal(G.nodeForces(node,materials,catalog).minimum.torqueNm,null,'Do not silently ignore an incomplete hydro criterion');
node.operating.hydro.medium = 'Вода';
material.grades[0].data.E = {};
assert.equal(G.nodeForces(node,materials,catalog).minimum.torqueNm,null,'Updated material base must propagate into the minimum');
console.log('OK: 18 зусиль/тисків Excel, 4 умови, нижня межа, одиниці моменту, мащення та неповні дані.');
